#!/usr/bin/env bash
# HARMONY build script.
#
#   ./build.sh                 library + tools (release)
#   ./build.sh -d              debug build
#   ./build.sh examples        library + every example in examples/
#   ./build.sh clean           removes build/, lib/ and bin/
#   ./build.sh -p /opt/harmony install
#
# Run ./build.sh -h for every option.

set -u

ROOT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
cd "$ROOT_DIR" || exit 1

# shellcheck source=bsbash/build_functions.sh
source "$ROOT_DIR/bsbash/build_functions.sh"
# shellcheck source=bsbash/find_functions.sh
source "$ROOT_DIR/bsbash/find_functions.sh"

usage() {
    cat <<EOF
Usage: ./build.sh [options] [targets]

Targets (default: lib tools):
  lib        static library lib/libharmony.a
  tools      bin/migration_profiler
  examples   builds every example with its own build.sh (needs lib)
  install    copies include/ and lib/ to the prefix given with -p
  clean      removes build/, lib/, bin/ and the examples' build output

Options:
  -r         release build (default): -O3
  -d         debug build: -O0 -g
  -j N       parallel compilations (default: number of cores)
  -p DIR     installation prefix for "install"
  -q         quiet: only errors
  -v         verbose: print every command
  -h         this help

Environment:
  MPICXX                    MPI C++ wrapper (default: mpicxx, mpic++ or mpiCC)
  OPENCL_INCLUDE_DIR        directory containing CL/cl.h
  OPENCL_LIBRARY_DIR        directory containing libOpenCL.so
  CL_TARGET_OPENCL_VERSION  OpenCL API version (default: 300)
  EXTRA_CXXFLAGS            appended to the compiler flags
EOF
}

BUILD_TYPE=release
JOBS=$(nproc 2>/dev/null || echo 4)
PREFIX=""
QUIET=0
VERBOSE=0

while getopts "rdj:p:qvh" opt; do
    case "$opt" in
        r) BUILD_TYPE=release ;;
        d) BUILD_TYPE=debug ;;
        j) JOBS=$OPTARG ;;
        p) PREFIX=$OPTARG ;;
        q) QUIET=1 ;;
        v) VERBOSE=1 ;;
        h) usage; exit 0 ;;
        *) usage; exit 1 ;;
    esac
done
shift $((OPTIND - 1))
TARGETS=("$@")
[ ${#TARGETS[@]} -eq 0 ] && TARGETS=(lib tools)

export QUIET VERBOSE JOBS

BUILD_DIR="$ROOT_DIR/build/$BUILD_TYPE"
LIB_DIR="$ROOT_DIR/lib"
BIN_DIR="$ROOT_DIR/bin"

clean() {
    PRINT_INFO "removing build/, lib/ and bin/"
    rm -rf "$ROOT_DIR/build" "$ROOT_DIR/lib" "$ROOT_DIR/bin"
    local ex
    for ex in "$ROOT_DIR"/examples/*/build.sh; do
        [ -f "$ex" ] && (cd "$(dirname "$ex")" && ./build.sh clean > /dev/null)
    done
    PRINT_OK "clean"
}

configure() {
    FIND_MPI || exit 1
    FIND_OPENCL || exit 1

    local opencl_version=${CL_TARGET_OPENCL_VERSION:-300}
    CXXFLAGS="-std=c++17 -Wall -Wextra -DCL_TARGET_OPENCL_VERSION=$opencl_version"
    # The C++ bindings of MPI are not used (and are deprecated).
    CXXFLAGS="$CXXFLAGS -DOMPI_SKIP_MPICXX -DMPICH_SKIP_MPICXX $OPENCL_CFLAGS"
    if [ "$BUILD_TYPE" = "debug" ]; then
        CXXFLAGS="$CXXFLAGS -O0 -g"
    else
        CXXFLAGS="$CXXFLAGS -O3 -DNDEBUG"
    fi
    CXXFLAGS="$CXXFLAGS ${EXTRA_CXXFLAGS:-}"
    LDFLAGS=""
    PRINT_INFO "build type: $BUILD_TYPE, $JOBS parallel jobs"
    write_config "$opencl_version"
}

# Flags used for the library, read by the build.sh of every example (and
# installed next to the library), so applications link with the same
# compiler and OpenCL.
write_config() {
    mkdir -p "$LIB_DIR"
    cat > "$LIB_DIR/harmony_config.sh" <<EOF
# Generated by HARMONY's build.sh. Sourced by applications' build scripts.
HARMONY_CXX="$CXX"
HARMONY_OPENCL_CFLAGS="$OPENCL_CFLAGS"
HARMONY_OPENCL_LIBS="$OPENCL_LIBS"
HARMONY_CL_TARGET_OPENCL_VERSION="$1"
EOF
}

install_files() {
    if [ -z "$PREFIX" ]; then
        PRINT_ERROR "install needs a prefix: ./build.sh -p /path/to/prefix install"
        exit 1
    fi
    mkdir -p "$PREFIX/include" "$PREFIX/lib" || exit 1
    cp -r "$ROOT_DIR/include/harmony" "$PREFIX/include/" || exit 1
    cp "$LIB_DIR/libharmony.a" "$LIB_DIR/harmony_config.sh" "$PREFIX/lib/" || exit 1
    PRINT_OK "installed to $PREFIX (include/harmony, lib/libharmony.a, lib/harmony_config.sh)"
}

build_examples() {
    local ex status=0
    for ex in "$ROOT_DIR"/examples/*/build.sh; do
        PRINT_INFO "${COLOR_BOLD}example $(basename "$(dirname "$ex")")${COLOR_RESET}"
        (cd "$(dirname "$ex")" && HARMONY_ROOT="$ROOT_DIR" ./build.sh) || status=1
    done
    return $status
}

# Targets that need the compiler.
needs_configure=0
for target in "${TARGETS[@]}"; do
    case "$target" in
        lib|tools|examples|install) needs_configure=1 ;;
        clean) ;;
        *) PRINT_ERROR "unknown target '$target'"; usage; exit 1 ;;
    esac
done
[ "$needs_configure" = "1" ] && configure

built_lib=0
for target in "${TARGETS[@]}"; do
    case "$target" in
        clean)
            clean ;;
        lib)
            ADD_SUBDIRECTORY src || exit 1
            built_lib=1 ;;
        tools)
            ADD_SUBDIRECTORY tools/migration_profiler || exit 1 ;;
        examples)
            [ "$built_lib" = "1" ] || ADD_SUBDIRECTORY src || exit 1
            built_lib=1
            build_examples || exit 1 ;;
        install)
            [ "$built_lib" = "1" ] || ADD_SUBDIRECTORY src || exit 1
            built_lib=1
            install_files ;;
    esac
done
